    @Test
    fun `MsgPack rejects oversized lengths and excessive depth`() {
        // bin32 claiming 0x7FFFFFFF bytes in a 5-byte buffer
        val evilBin = byteArrayOf(0xC6.toByte(), 0x7F, 0xFF.toByte(), 0xFF.toByte(), 0xFF.toByte())
        assertFailsWith<IllegalArgumentException> { MsgPack.decode(evilBin) }

        // array32 claiming 1_000_000 elements in a 5-byte buffer
        val evilArr = byteArrayOf(0xDD.toByte(), 0x00, 0x0F, 0x42, 0x40)
        assertFailsWith<IllegalArgumentException> { MsgPack.decode(evilArr) }

        // depth 20 nested arrays > MAX_DEPTH (16)
        val deep = ByteArray(21) { 0x91.toByte() }.also { it[20] = 0xC0.toByte() }
        assertFailsWith<IllegalArgumentException> { MsgPack.decode(deep) }
    }
