    private val alicePub = RnsCrypto.hexToBytes("14ca9e4d387bccf35746e0407daaacc6b28a4f8445ef5a5158894db983e240707d59c5623dd40a74aa4d5a32ac645d3b3f95daeae4c22be25476dd6a486f7382")

    @Test
    fun `signalling bytes match Python RNS 1_6_0 Link_signalling_bytes`() {
        assertEquals("202000", RnsCrypto.bytesToHex(RnsCrypto.encodeSignalling(8192, RnsLinkMode.AES256_CBC)))
        assertEquals(8192 to RnsLinkMode.AES256_CBC, RnsCrypto.decodeSignalling(RnsCrypto.hexToBytes("202000")))

        val sig32k = RnsCrypto.encodeSignalling(32768, RnsLinkMode.AES256_CBC)
        assertEquals("208000", RnsCrypto.bytesToHex(sig32k))
        assertEquals(32768 to RnsLinkMode.AES256_CBC, RnsCrypto.decodeSignalling(sig32k))

        val sig500 = RnsCrypto.encodeSignalling(500, RnsLinkMode.AES256_CBC)
        assertEquals(500 to RnsLinkMode.AES256_CBC, RnsCrypto.decodeSignalling(sig500))
    }

    @Test
    fun `link request uses LINKREQUEST packet type 0x02 and 0x52`() {
        val destHex = "0102030405060708090a0b0c0d0e0f10"
        val link = RnsLinkSession(destHex, alicePub)
        val h1 = link.buildLinkRequestPacket(transportId16 = null)
        assertEquals(0x02, h1[0].toInt() and 0xFF)
        assertEquals(RnsPacketType.LINKREQUEST, h1[0].toInt() and 0x03)

        val tid = ByteArray(16) { 0xAA.toByte() }
        val h2 = link.buildLinkRequestPacket(transportId16 = tid)
        assertEquals(0x52, h2[0].toInt() and 0xFF)
        assertEquals(RnsPacketType.LINKREQUEST, h2[0].toInt() and 0x03)
    }

    @Test
    fun `link proof requires known destinationPubKey64 and valid Ed25519 signature`() {
        val destHex = "0102030405060708090a0b0c0d0e0f10"
        val linkWithoutPub = RnsLinkSession(destHex, destinationPubKey64 = null)
        assertNull(linkWithoutPub.handleLinkProof(ByteArray(99)))

        val peerEdPriv = Ed25519PrivateKeyParameters(ByteArray(32) { 0x11 }, 0)
        val peerEdPub = peerEdPriv.generatePublicKey().encoded
        val peerXPriv = X25519PrivateKeyParameters(ByteArray(32) { 0x22 }, 0)
        val peerXPub = peerXPriv.generatePublicKey().encoded
        val peerPub64 = peerXPub + peerEdPub

        val link = RnsLinkSession(destHex, peerPub64)
        val sig3 = RnsCrypto.encodeSignalling(32768, RnsLinkMode.AES256_CBC)
        val signed = link.linkIdBytes + peerXPub + peerEdPub + sig3
        val signer = Ed25519Signer().apply { init(true, peerEdPriv); update(signed, 0, signed.size) }
        val sig64 = signer.generateSignature()

        // Corrupt signature -> rejected
        val badSig = sig64.copyOf().also { it[0] = (it[0].toInt() xor 0xFF).toByte() }
        assertNull(link.handleLinkProof(badSig + peerXPub + sig3))
        assertEquals(RnsLinkSession.State.PENDING, link.state)

        // Valid signature -> ACTIVE + LRRTT packet
        val rttPkt = link.handleLinkProof(sig64 + peerXPub + sig3)
        assertNotNull(rttPkt)
        assertEquals(RnsLinkSession.State.ACTIVE, link.state)
        assertEquals(32768, link.negotiatedMtu)
    }

    @Test
    fun `keepalive is unencrypted 0xFA 0xFF and linkclose requires decrypted linkId`() {
        val peerEdPriv = Ed25519PrivateKeyParameters(ByteArray(32) { 0x33 }, 0)
        val peerEdPub = peerEdPriv.generatePublicKey().encoded
        val peerXPriv = X25519PrivateKeyParameters(ByteArray(32) { 0x44 }, 0)
        val peerXPub = peerXPriv.generatePublicKey().encoded
        val link = RnsLinkSession("0102030405060708090a0b0c0d0e0f10", peerXPub + peerEdPub)
        val sig3 = RnsCrypto.encodeSignalling(32768, RnsLinkMode.AES256_CBC)
        val signed = link.linkIdBytes + peerXPub + peerEdPub + sig3
        val sig64 = Ed25519Signer().apply { init(true, peerEdPriv); update(signed, 0, signed.size) }.generateSignature()
        assertNotNull(link.handleLinkProof(sig64 + peerXPub + sig3))

        val ka = link.buildKeepalivePacket()
        assertNotNull(ka)
        assertEquals(RnsContext.KEEPALIVE, ka[18])
        assertEquals(0xFF.toByte(), ka[19])
        assertEquals(20, ka.size)

        // Unencrypted or wrong linkId LINKCLOSE must NOT close the link
        assertFalse(link.verifyAndHandleLinkClose(link.linkIdBytes))
        assertEquals(RnsLinkSession.State.ACTIVE, link.state)

        // Request ID equals truncated packet hash
        val (reqId, reqPkt) = link.buildRequestPacket("/get", LxmfCodec.buildGetMessagesRequest())!!
        assertContentEquals(RnsCrypto.packetTruncatedHash(reqPkt), reqId)

        // Valid encrypted LINKCLOSE closes the link
        val closePkt = link.buildLinkClosePacket()!!
        val closeCiphertext = closePkt.copyOfRange(19, closePkt.size)
        assertTrue(link.verifyAndHandleLinkClose(closeCiphertext))
        assertEquals(RnsLinkSession.State.CLOSED, link.state)
    }

